import assert from 'node:assert/strict'
import { chromium } from 'playwright-core'
import JSZip from 'jszip'

const baseURL = process.env.E2E_BASE_URL || 'http://127.0.0.1:5173/'
const executablePath = process.env.E2E_BROWSER_PATH || '/usr/bin/chromium'
const browser = await chromium.launch({ executablePath, headless: true, args: ['--no-sandbox', '--disable-dev-shm-usage'] })
const errors = []
const desktop = await browser.newContext({ viewport: { width: 1440, height: 900 }, acceptDownloads: true })
const page = await desktop.newPage()
page.on('pageerror', error => errors.push(error.message))
const replaceEditor = async text => {
  const editor = page.locator('.cm-content')
  await editor.click()
  await editor.press('Control+A')
  await page.keyboard.insertText(text)
}
try {
  await page.goto(baseURL, { waitUntil: 'networkidle' })
  await page.locator('.project-switcher').click()
  await page.getByRole('dialog', { name: 'Projects dashboard' }).getByRole('button', { name: 'Create project', exact: true }).click()
  const create = page.getByRole('dialog', { name: 'Create a new project' })
  await create.getByLabel('PROJECT NAME').fill('Browser test website')
  await create.getByRole('button', { name: 'Create project' }).click()
  await page.locator('.project-switcher').getByText('Browser test website').waitFor()

  await page.locator('input[type=file][multiple]').setInputFiles({ name: 'pixel 1.png', mimeType: 'image/png', buffer: Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+/aWQAAAAASUVORK5CYII=', 'base64') })
  await page.getByText('Imported 1 file.').waitFor()
  await page.locator('.sidebar').getByRole('button', { name: 'New file', exact: true }).click()
  const newFile = page.getByRole('dialog', { name: 'New file' })
  await newFile.getByLabel('FILE PATH').fill('docs/notes.txt')
  await newFile.getByRole('button', { name: 'Create file' }).click()
  await replaceEditor('A nested project note.')
  await page.getByRole('tab', { name: /index.html/ }).locator('.tab-name').click()
  const html = '<!doctype html><html lang="en"><head><title>Browser test</title><link rel="stylesheet" href="./styles.css"></head><body><h1 id="message">Hello from the editor</h1><img id="pixel" src="./pixel%201.png"><button id="action">Change text</button><script src="./script.js"></script></body></html>'
  await replaceEditor(html)
  await page.getByRole('tab', { name: /styles.css/ }).locator('.tab-name').click()
  await replaceEditor('#message { color: rgb(1, 2, 3); }')
  await page.getByRole('tab', { name: /script.js/ }).locator('.tab-name').click()
  await replaceEditor("document.querySelector('#action').addEventListener('click', () => { document.querySelector('#message').textContent = 'Clicked!'; });\ntry { localStorage.setItem('preview-probe','bad'); } catch (error) { console.log('Storage blocked as expected'); }\ntry { parent.document.body.setAttribute('data-compromised','yes'); } catch (error) { console.log('Parent blocked as expected'); }\nconsole.log('Browser test script ran');\nsetTimeout(() => { throw new Error('Browser test error'); }, 50);")
  const frame = page.frameLocator('iframe[title="Sandboxed live preview"]')
  await frame.locator('#message').waitFor()
  await page.waitForFunction(() => document.querySelector('iframe[title="Sandboxed live preview"]')?.getAttribute('sandbox') === 'allow-scripts')
  await frame.getByRole('button', { name: 'Change text' }).click()
  await frame.getByText('Clicked!').waitFor()
  assert.equal(await frame.locator('#message').evaluate(element => getComputedStyle(element).color), 'rgb(1, 2, 3)')
  await page.waitForFunction(() => [...document.querySelectorAll('.console-line')].some(row => row.textContent?.includes('Browser test error')))
  await page.waitForFunction(() => [...document.querySelectorAll('.console-line')].some(row => row.textContent?.includes('Storage blocked as expected')))
  await frame.locator('#pixel').evaluate(async image => { if (!image.complete) await new Promise(resolve => image.addEventListener('load', resolve, { once: true })) })
  assert.equal(await frame.locator('#pixel').evaluate(image => image.naturalWidth), 1)
  assert.equal(await page.evaluate(() => localStorage.getItem('preview-probe')), null)
  assert.equal(await page.locator('body').getAttribute('data-compromised'), null)
  await page.waitForFunction(() => [...document.querySelectorAll('.console-line')].some(row => row.textContent?.includes('Parent blocked as expected')))
  await page.getByText('All changes saved').waitFor({ timeout: 7000 })
  await page.reload({ waitUntil: 'networkidle' })
  await page.frameLocator('iframe[title="Sandboxed live preview"]').getByText('Hello from the editor').waitFor()
  await page.frameLocator('iframe[title="Sandboxed live preview"]').getByRole('button', { name: 'Change text' }).click()
  await page.frameLocator('iframe[title="Sandboxed live preview"]').getByText('Clicked!').waitFor()
  const popupPromise = desktop.waitForEvent('page')
  await page.getByRole('button', { name: 'Open preview in new tab' }).click()
  const popup = await popupPromise
  await popup.waitForLoadState('domcontentloaded')
  await popup.frameLocator('iframe[title="Isolated project preview"]').getByText('Hello from the editor').waitFor()
  await popup.close()
  await page.getByRole('button', { name: 'Project actions' }).click()
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Export project ZIP' }).click()
  const download = await downloadPromise
  const zipBytes = await (await download.createReadStream()).toArray().then(chunks => Buffer.concat(chunks))
  const archive = await JSZip.loadAsync(zipBytes)
  assert.match(await archive.file('index.html').async('string'), /Hello from the editor/)
  assert.match(await archive.file('styles.css').async('string'), /rgb\(1, 2, 3\)/)
  assert.match(await archive.file('script.js').async('string'), /Browser test script ran/)
  assert.ok(archive.file('pixel 1.png'))
  assert.equal(await archive.file('docs/notes.txt').async('string'), 'A nested project note.')
  await page.getByRole('button', { name: 'Project actions' }).click()
  const [chooser] = await Promise.all([page.waitForEvent('filechooser'), page.locator('.project-quick-menu').getByRole('button', { name: 'Import ZIP', exact: true }).click()])
  await chooser.setFiles({ name: 'Restored.zip', mimeType: 'application/zip', buffer: zipBytes })
  await page.locator('.project-switcher').getByText('Restored').waitFor()
  await page.frameLocator('iframe[title="Sandboxed live preview"]').getByText('Hello from the editor').waitFor()
  console.log('PASS desktop: create, nested files, asset import, edit HTML/CSS/JS, isolated preview, console errors, autosave/reload and ZIP export/import')

  const mobile = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true })
  const phone = await mobile.newPage()
  phone.on('pageerror', error => errors.push(error.message))
  await phone.goto(baseURL, { waitUntil: 'networkidle' })
  await phone.getByRole('button', { name: 'Open explorer' }).click()
  await phone.locator('.mobile-sidebar-nav').getByRole('button', { name: 'Search project' }).click()
  await phone.getByRole('textbox', { name: 'Search project' }).fill('html')
  await phone.locator('.search-result').first().waitFor()
  await phone.locator('.mobile-sidebar-nav').getByRole('button', { name: 'Snippets' }).click()
  await phone.getByRole('button', { name: /CSS reset/ }).click()
  await phone.getByRole('button', { name: 'Insert braces' }).click()
  await phone.getByRole('button', { name: 'Live preview' }).click()
  await phone.frameLocator('iframe[title="Sandboxed live preview"]').locator('body').waitFor()
  await phone.getByRole('button', { name: 'Mobile viewport' }).click()
  assert.equal(await phone.getByRole('button', { name: 'Mobile viewport' }).getAttribute('aria-pressed'), 'true')
  await phone.getByRole('button', { name: 'Close preview' }).click()
  assert.equal(await phone.getByRole('button', { name: 'Insert braces' }).isVisible(), true)
  console.log('PASS mobile: responsive drawer, project search, snippets, accessory keys and fullscreen preview')
  await mobile.close()
  if (process.env.E2E_OFFLINE === '1') {
    const offlineContext = await browser.newContext()
    const offlinePage = await offlineContext.newPage()
    await offlinePage.goto(baseURL, { waitUntil: 'networkidle' })
    await offlinePage.evaluate(async () => { await navigator.serviceWorker.ready })
    await offlinePage.reload({ waitUntil: 'networkidle' })
    assert.equal(await offlinePage.evaluate(() => !!navigator.serviceWorker.controller), true)
    await offlineContext.setOffline(true)
    await offlinePage.reload({ waitUntil: 'domcontentloaded' })
    await offlinePage.locator('.cm-content').waitFor()
    console.log('PASS offline: cached production shell opens with a real editor')
    await offlineContext.close()
  }
  assert.ok(errors.includes('Browser test error'), 'Expected preview error was observed')
  const unexpected = errors.filter(message => message !== 'Browser test error')
  assert.deepEqual(unexpected, [], `Unexpected application errors: ${unexpected.join('; ')}`)
} finally {
  await browser.close()
}
